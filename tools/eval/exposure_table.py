"""Generate the F-3 exposure table: how much of each H6 guard patrol overlaps the
patrols the PPO rival trained against (decision #75; T08 Gate 2).

    python3 tools/eval/exposure_table.py              # the frozen H6 (hash checked)

Training used only the default arena guards (`pop/arena.py` GUARD_POSTS: rooms 4
and 5, columns 1 to 8). A post is *full* when every cell of its patrol was a
training patrol cell, *partial* when some were, *none* when none were (a room that
had no guard in training, or a different stretch). A start is labelled
"training-like" when both its posts are full, "partly training-like" when any post
overlaps, and "unseen layout" otherwise. The table is generated so the claim in
docs/final/evaluation/PROTOCOL.md is never hand-written. Evaluator-side only: it
reads the frozen set and the arena map, never a policy or a run.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

from evaluation import manifest  # noqa: E402
from pop import arena  # noqa: E402


def training_cells() -> set[tuple[int, int, int]]:
    cells = set()
    for room, row, (c0, c1), _ in arena.GUARD_POSTS.values():
        cells |= {(room, row, c) for c in range(c0, c1 + 1)}
    return cells


def post_overlap(post, cells: set) -> str:
    room, row, (c0, c1), _ = post
    covered = {(room, row, c) for c in range(c0, c1 + 1)}
    hit = len(covered & cells)
    return "full" if hit == len(covered) else "partial" if hit else "none"


def label(kinds: list[str]) -> str:
    if kinds and all(k == "full" for k in kinds):
        return "training-like"
    return "partly training-like" if any(k != "none" for k in kinds) else "unseen layout"


def exposure(starts: list[dict]) -> dict:
    cells = training_cells()
    per_start = []
    total = {"full": 0, "partial": 0, "none": 0}
    for st in starts:
        kinds = [post_overlap(g, cells) for g in st["guards"].values()]
        for k in kinds:
            total[k] += 1
        per_start.append({"start": st["id"], "posts": kinds, "label": label(kinds)})
    return {**total, "posts": sum(total.values()), "per_start": per_start}


def render(starts: list[dict]) -> str:
    t = exposure(starts)
    lines = ["# H6 exposure to the training guard patrols (generated by tools/eval/exposure_table.py)",
             "", f"Posts: {t['posts']}; full overlap {t['full']}, partial {t['partial']}, "
             f"none {t['none']}.", "", "| start | post 1 | post 2 | label |", "|---|---|---|---|"]
    for r in t["per_start"]:
        p = (r["posts"] + ["-", "-"])[:2]
        lines.append(f"| {r['start']} | {p[0]} | {p[1]} | {r['label']} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    manifest.verify_heldout()
    starts = json.loads(manifest.HELDOUT_PATH.read_text())["scenarios"][0]["starts"]
    print(render(starts), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
